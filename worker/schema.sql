CREATE TABLE IF NOT EXISTS posts(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT,image TEXT,category TEXT,genres TEXT,year TEXT,synopsis TEXT);
CREATE TABLE IF NOT EXISTS episodes(id INTEGER PRIMARY KEY AUTOINCREMENT,post_id INTEGER,season TEXT,ep TEXT,dl_link TEXT,play_link TEXT,quality TEXT);
CREATE TABLE IF NOT EXISTS shorteners(id INTEGER PRIMARY KEY AUTOINCREMENT,home TEXT,api TEXT);
CREATE TABLE IF NOT EXISTS users(email TEXT PRIMARY KEY,pass TEXT,session TEXT);
CREATE TABLE IF NOT EXISTS settings(k TEXT PRIMARY KEY,v TEXT);
CREATE TABLE IF NOT EXISTS flows(f TEXT PRIMARY KEY,ep INTEGER,ts INTEGER,used INTEGER DEFAULT 0);
